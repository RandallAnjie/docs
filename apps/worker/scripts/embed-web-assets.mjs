import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const workerSrc = dirname(
  fileURLToPath(new URL('../src/generated-web-assets.ts', import.meta.url)),
);
const distDir = fileURLToPath(new URL('../../web/dist', import.meta.url));
const outFile = join(workerSrc, 'generated-web-assets.ts');

function walk(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

function mimeType(file) {
  switch (extname(file)) {
    case '.js':
    case '.mjs':
      return 'application/javascript; charset=utf-8';
    case '.css':
      return 'text/css; charset=utf-8';
    case '.html':
      return 'text/html; charset=utf-8';
    case '.svg':
      return 'image/svg+xml';
    case '.woff2':
      return 'font/woff2';
    case '.json':
    case '.webmanifest':
      return 'application/manifest+json';
    default:
      return 'application/octet-stream';
  }
}

function isText(file) {
  return ['.js', '.mjs', '.css', '.html', '.svg', '.json', '.webmanifest', '.txt'].includes(
    extname(file),
  );
}

const files = walk(distDir).filter((file) => {
  const extension = extname(file);
  if (file.endsWith('.map') || file.endsWith('.html')) return false;
  if (extension === '.ttf' || extension === '.woff') return false;
  return true;
});
const htmlFile = join(distDir, 'index.html');
const html = existsSync(htmlFile)
  ? readFileSync(htmlFile, 'utf8')
  : '<!doctype html><html><head><meta charset="UTF-8" /><title>Rdocs</title></head><body><div id="root"></div></body></html>';

const assets = {};
for (const file of files) {
  const path = `/${relative(distDir, file).replaceAll('\\', '/')}`;
  const type = mimeType(file);
  if (isText(file)) {
    assets[path] = { type, encoding: 'utf8', body: readFileSync(file, 'utf8') };
  } else {
    assets[path] = { type, encoding: 'base64', body: readFileSync(file).toString('base64') };
  }
}

mkdirSync(workerSrc, { recursive: true });
writeFileSync(
  outFile,
  `// Generated by embed-web-assets.mjs. Do not edit.
export const webHtml = ${JSON.stringify(html)};
export const webAssets: Record<
  string,
  { type: string; encoding: 'utf8' | 'base64'; body: string }
> = ${JSON.stringify(assets, null, 2)};
`,
);
console.log(`embedded web html (${Buffer.byteLength(html)} bytes) and ${files.length} assets`);
